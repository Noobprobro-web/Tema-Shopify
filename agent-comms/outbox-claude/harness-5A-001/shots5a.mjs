import { chromium } from 'playwright';
const b = await chromium.launch(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {});
const site = process.env.SITE || 'site-en';
const p = await b.newPage({ viewport: { width: 1280, height: 900 } });
await p.goto(`http://127.0.0.1:8105/${site}/collection.html`, { waitUntil: 'networkidle' });
await p.evaluate(() => { document.documentElement.style.scrollBehavior = 'auto'; });
const grid = p.locator('[data-product-list]');
await grid.scrollIntoViewIfNeeded();
await p.locator('article[data-product-id="103"] [data-card-swatch][data-swatch-value="Bone"]').click();
await p.locator('article[data-product-id="103"] [data-quick-buy-trigger]').click();
await p.mouse.move(1, 1); await p.waitForTimeout(900);
const box = await p.locator('article[data-product-id="101"]').boundingBox();
await p.screenshot({ path: `shots/shot-desktop-${site}.png`, clip: { x: box.x - 10, y: box.y - 10, width: 1280 - box.x, height: 760 } });
await p.locator('.facet').first().screenshot({ path: `shots/shot-facet-${site}.png` });
const m = await b.newPage({ viewport: { width: 390, height: 740 } });
await m.goto(`http://127.0.0.1:8105/${site}/collection.html`, { waitUntil: 'networkidle' });
await m.locator('article[data-product-id="103"]').scrollIntoViewIfNeeded();
await m.waitForTimeout(900);
await m.screenshot({ path: `shots/shot-mobile-cards-${site}.png` });
await m.locator('article[data-product-id="103"] [data-quick-buy-trigger]').click();
await m.waitForTimeout(900);
await m.screenshot({ path: `shots/shot-mobile-sheet-${site}.png` });
await b.close();
