import fs from 'node:fs';
import { STORES, launch, unlock } from '../../harness-AUDIT-FINAL-002/lib.mjs';
const BASE = STORES.edition.url;
const out = {};
const browser = await launch();
const go = async (page, p) => { const r = await page.goto(BASE + p, { waitUntil: 'load', timeout: 60000 }); await page.waitForTimeout(1800); return r && r.status(); };
let context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
await unlock(context, BASE);
let page = await context.newPage();
await go(page, '/');
out.homeLeftEdges = await page.evaluate(() => [...document.querySelectorAll('[id^="shopify-section-"]')].map(s => { const t = s.querySelector('h1,h2,.eyebrow,img,a'); return s.id.split('__').pop() + ':' + (t ? Math.round(t.getBoundingClientRect().left) : '-'); }));
await go(page, '/search?q=leather');
await page.screenshot({ path: 'search-q-leather-desktop-top-viewport.png' });
out.paperweight = await page.evaluate(async () => { const p = await (await fetch('/products/milled-brass-paperweight.js')).json(); return { images: p.images.length, variants: p.variants.map(v => v.title + ' media=' + (v.featured_image ? 'yes' : 'none')) }; });
out.collectionsJson = await page.evaluate(async () => (await (await fetch('/collections.json')).json()).collections.map(c => c.handle + ' | ' + c.title + ' | ' + c.products_count));
await context.close();
context = await browser.newContext({ viewport: { width: 390, height: 844 } });
await unlock(context, BASE);
page = await context.newPage();
await go(page, '/');
out.tabs = await page.evaluate(() => { const t = document.querySelector('.curated-showcase__tab'); const list = t?.parentElement; const cs = list && getComputedStyle(list); return list && { listCls: list.className, overflowX: cs.overflowX, sw: list.scrollWidth, cw: list.clientWidth, mask: cs.maskImage || cs.webkitMaskImage, tabs: [...list.children].map(c => c.innerText.trim() + ' r=' + Math.round(c.getBoundingClientRect().right)) }; });
await page.locator('.curated-showcase__tab').first().scrollIntoViewIfNeeded();
await page.evaluate(() => window.scrollBy(0, -120)); await page.waitForTimeout(1500);
await page.screenshot({ path: 'home-mobile-showcase-tabs.png' });
await context.close();
await browser.close();
fs.writeFileSync('results-07.json', JSON.stringify(out, null, 1));
console.log(JSON.stringify(out, null, 1));
